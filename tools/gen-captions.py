def size_role(kg):
    """体重 → 体格角色（一句用于拼接的短句）"""
    if kg < 0.3:
        return "小得可以当零食"
    if kg < 2:
        return "个头不大"
    if kg < 8:
        return "中等体型"
    if kg < 60:
        return "体格可观"
    return "体型惊人"


def features_of(f):
    """特征位 → **能嵌进句子的短名词**。

    ⚠️ 必须是名词短语（「那排硬棘」），不能是描述句（「背上一排硬棘」）——
       实测把描述句硬塞进句式里会拼出「尤其是背上一排硬棘，在光里格外清楚」这种读不通的句子。
       描述句留给需要独立成句的地方（见 `feature_sentence()`）。
    """
    out = []
    if f.get("spiny"):   out.append("那排硬棘")
    if f.get("barbels"): out.append("嘴边那几根须")
    if f.get("glow"):    out.append("自带的那盏灯")
    if f.get("teeth"):   out.append("那口看得见的牙")
    if f.get("lure"):    out.append("额头前那根发光的小杆子")
    if f.get("stripes"): out.append("身上那几道竖纹")
    if f.get("spots"):   out.append("满身的斑点")
    return out


def feature_sentence(f):
    """特征位 → **独立成句**的版本（给需要起一句的地方用）"""
    if f.get("spiny"):   return "背上那排硬棘始终立着。"
