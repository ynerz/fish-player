def stable_pick(fid, salt, options):
    """按鱼 id 做**确定性**选择 —— 同一条鱼每次生成结果一样（可复现是硬要求）。

    ⚠️ 取 **8 个字节**做取模，不能只取首字节 `h[0]`：
       首字节只有 0~255 种取值，取模后**分布明显不均** ——
       实测 C 池 30 项、362 条鱼，理论上每句该用 12 次，实际最热的用了 **29 次**
       （偏差一倍多），直接推高了「同一句话被反复看到」的概率。
    """
    h = hashlib.md5((str(fid) + "|" + salt).encode("utf-8")).digest()
    return options[int.from_bytes(h[:8], "big") % len(options)]


def compose(f, slot, pools, attempt=0):
    """**多片段组合** —— 每个片段位从一个池里取一项，拼起来。

    ⚠️ 为什么必须这样：单池抽一句的做法，362 条鱼摊下来最热的句子会重复 **130 次**
       （实测：3694 句只有 455 种）。改成一个文案由 3~4 个**独立片段位**拼成，
       组合数就从「池子大小」变成「各池大小之积」—— 重复率才压得下来。

    ⚠️ `attempt` 是**去重重试**用的：换一个 attempt 就换一整组片段。
       用户口径「**每条鱼的介绍都不一样**」—— 组合数有限（各池之积），
       982 段文案按生日悖论必然有碰撞，所以光靠「组合空间大」不够，
       必须在生成时检测 + 重试（见 `gen_unique()`）。
    """
    out = []
    for i, pool in enumerate(pools):
        if pool:
            out.append(stable_pick(f["id"], "%s-s%d-a%d" % (slot, i, attempt), pool))
    return "".join(out)


def gen_unique(f, slot, builder, seen):
    """生成一条**没出现过**的文案 —— 撞车就换一整组片段重试。

    ⚠️ 这是「每条鱼的介绍都不一样」的保证手段，不是可选项：
       组合数有限 + 982 段文案 = 必然有碰撞（生日悖论）。
       实测不加这一步时，982 段里有 17 段完全相同。
    """
    for attempt in range(40):
        txt = builder(f, attempt)
        if txt not in seen:
            seen.add(txt)
            return txt
    # 兜底：40 次都撞（池子实在太平），宁可重复也不能返回空
    txt = builder(f, 0)
    seen.add(txt)
    fallback.append("%s-%s" % (f.get("id"), slot))
    return txt


