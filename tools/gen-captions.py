def audit(rows):
    """重复率审计 —— 模板化生成最容易翻车的地方，每次改完片段池都该跑一遍。

    ⚠️ 要**同时看两个指标**，只看一个会误判：
       · **整段重复** —— 玩家在图鉴里看到的就是一整段，这个必须接近 0
       · **单句重复** —— 单句一定会重复（池子有多大，重复次数就有多少），
         但它决定了「连看几条会不会发现是套的」，所以最高次数要压到一个可接受的量级
    """
    segs = [txt for _, txt in rows]
    c_seg = collections.Counter(segs)
    dup_seg = [(s, n) for s, n in c_seg.most_common(10) if n > 1]

    sents = []
    for s in segs:
        sents += [x.strip() for x in re.split(r"(?<=[。！？])", s) if len(x.strip()) > 12]
    c_s = collections.Counter(sents)
    dup_s = [(s, n) for s, n in c_s.most_common(20) if n > 1]

    print("── 整段 ──")
    print("  %d 段 ｜ 去重 %d ｜ **完全重复 %d 段**（重复率 %.2f%%）"
          % (len(segs), len(c_seg), len(segs) - len(c_seg),
             100.0 * (len(segs) - len(c_seg)) / max(1, len(segs))))
    for s, n in dup_seg[:4]:
        print("    ×%-3d %s" % (n, s[:66].replace("\n", " ")))
    print("── 单句 ──")
    print("  %d 句 ｜ 去重 %d ｜ 最高重复 %d 次 ｜ 不同句 %d 种"
          % (len(sents), len(c_s), dup_s[0][1] if dup_s else 0, len(c_s)))
    for s, n in dup_s[:6]:
        print("    ×%-3d %s" % (n, s[:62]))
    return len(segs) - len(c_seg)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", default="")
    ap.add_argument("--audit", action="store_true")
    args = ap.parse_args()

    import importlib.util
    spec = importlib.util.spec_from_file_location("genart", os.path.join(ROOT, "tools", "gen-art.py"))
    ga = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ga)
    fish = ga.load_fish()

    seen, uniq = set(), []
    for f in fish:
        if f["id"] in seen:
            continue
        seen.add(f["id"]); uniq.append(f)

    only = set(x.strip() for x in args.list.split(",") if x.strip())
    if only:
        uniq = [f for f in uniq if f["id"] in only]

    # ⚠️ 用 gen_unique 生成并**把结果存下来**：
    #    输出时不能重新生成一遍 —— 那会绕过去重，又冒出重复。
    rows = []          # [(id, key, 文本)]
    seen = set()
    for f in uniq:
        rar = f.get("rar", 0)
        for key in COVER.get(rar, COVER[0]):
            txt = gen_unique(f, key, lambda ff, at, k=key: CAPTIONS[k](ff, at), seen)
            rows.append((f["id"], key, txt))

    print("文案 %d 段（%d 条鱼）" % (len(rows), len(uniq)))
    audit([(k, t) for _, k, t in rows])
    if fallback:
        print("⚠️ 兜底命中（池子太小，40 次重试都撞）：%s" % ", ".join(fallback[:8]))
    if args.audit:
        return

    byid = {}
    for fid, key, txt in rows:
        byid.setdefault(fid, {})[key] = txt

    L = ["# 图鉴文案（%d 条鱼 / %d 段）\n" % (len(uniq), len(rows)),
         "> 由 `tools/gen-captions.py` 生成，**不要手改**（改风格请改生成器的片段池）。",
         "> **档位覆盖**：普通 / 稀有只写「原色 + 闪光」；史诗 / 传说写全五档（用户口径）。",
         "> **五档角度**：原色→习性 ｜ 亮色→视觉奇观 ｜ 白化→生存代价 ｜ "
         "黄金→人的反应 ｜ 闪光→光本身 + 结合本鱼特点。",
         "> **去重保证**：生成时检测整段重复并换组合重试，所以**每一条鱼的介绍都不一样**。\n"]
    for f in uniq:
        rar = f.get("rar", 0)
        L.append("## %s %s（%s · %s）" % (f["id"], f["name"], RAR_CN.get(rar, "?"), f.get("shape", "")))
        for key in COVER.get(rar, COVER[0]):
            txt = byid.get(f["id"], {}).get(key, "")
            # ⚠️ 史诗 / 传说档分段：句子多，挤成一段读起来喘不过气。
            #    只在输出处做一次，不放进每个 cap_* 里。
            if rar >= 2:
                txt = txt.replace("。", "。\n\n", 1).strip()
            L.append("- **%s**：%s" % (MORPH_CN[key], txt))
        L.append("")

    out = os.path.join(ROOT, "docs", "图鉴文案.md")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("已写出：%s" % out)


